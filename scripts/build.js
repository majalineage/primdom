/**
 * Build Script for PrimDom: Packages modular source files and hero photos into a standalone js/bundle.js
 * Enables double-click execution directly via file:/// protocol without any local web server.
 */

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');

console.log('📦 Building standalone PrimDom bundle...');

// 1. Read day/night hero images and convert to Base64 Data URLs
const dayPath = path.join(rootDir, 'assets/images/hero/day.jpg');
const nightPath = path.join(rootDir, 'assets/images/hero/night.jpg');

if (!fs.existsSync(dayPath) || !fs.existsSync(nightPath)) {
  console.error('❌ Missing day.jpg or night.jpg in assets/images/hero/!');
  process.exit(1);
}

const dayBase64 = 'data:image/jpeg;base64,' + fs.readFileSync(dayPath).toString('base64');
const nightBase64 = 'data:image/jpeg;base64,' + fs.readFileSync(nightPath).toString('base64');

console.log(`✓ Loaded day.jpg (${(dayBase64.length / 1024 / 1024).toFixed(2)} MB data URL)`);
console.log(`✓ Loaded night.jpg (${(nightBase64.length / 1024 / 1024).toFixed(2)} MB data URL)`);

// 2. Read Source Files
const shadersCode = fs.readFileSync(path.join(rootDir, 'js/shaders.js'), 'utf-8');
const configCode = fs.readFileSync(path.join(rootDir, 'js/config.js'), 'utf-8');
const heroWebGLCode = fs.readFileSync(path.join(rootDir, 'js/heroWebGL.js'), 'utf-8');
const galleryCode = fs.readFileSync(path.join(rootDir, 'js/gallery.js'), 'utf-8');
const mainCode = fs.readFileSync(path.join(rootDir, 'js/main.js'), 'utf-8');

// Helper to strip ES imports & exports
function stripImportsExports(code) {
  return code
    .replace(/^import\s+.*?;\s*$/gm, '')
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*['"].*?['"];?\s*$/gm, '')
    .replace(/^export\s+(const|class|function|let|var)\s+/gm, '$1 ')
    .replace(/^export\s*\{[\s\S]*?\};?\s*$/gm, '')
    .replace(/^export\s+default\s+/gm, '');
}

// 3. Assemble Standalone Bundle
const bundleContent = `/**
 * PrimDom Standalone WebGL Bundle
 * Auto-generated by scripts/build.js
 * Works completely offline and via file:/// protocol without a web server.
 */
(function() {
  'use strict';

  // --- Embedded Hero Textures (Data URLs for CORS-free local WebGL) ---
  const EMBEDDED_HERO_ASSETS = {
    dayImage: ${JSON.stringify(dayBase64)},
    nightImage: ${JSON.stringify(nightBase64)}
  };

  // --- Shaders ---
  ${stripImportsExports(shadersCode)}

  // --- Configuration ---
  ${stripImportsExports(configCode)}

  // Inject embedded base64 hero textures so WebGL works directly via file:///
  CONFIG.hero.dayImage = EMBEDDED_HERO_ASSETS.dayImage;
  CONFIG.hero.nightImage = EMBEDDED_HERO_ASSETS.nightImage;

  // --- WebGL Hero Engine ---
  ${stripImportsExports(heroWebGLCode)}

  // --- House Gallery Component ---
  ${stripImportsExports(galleryCode)}

  // --- Main Application Coordinator ---
  ${stripImportsExports(mainCode)}

})();
`;

const outputPath = path.join(rootDir, 'js/bundle.js');
fs.writeFileSync(outputPath, bundleContent, 'utf-8');

console.log(`✅ Bundle generated: js/bundle.js (${(bundleContent.length / 1024 / 1024).toFixed(2)} MB)`);

